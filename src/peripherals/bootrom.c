/*
--------- GB BOOTROM ---------
The GB Bootrom is represented by a memory chip internal to the cpu. 

This memory can only be read (write to this area should be ignored)!
The bootrom also consist of a status register => BOOT which is mapped to address 0xFF50.

The assembly program of the bootrom was represented here in byte format for simplicity purpose 
with the rest of the emulator code.

Source for bootrom assembly dump: https://gbdev.gg8.se/wiki/articles/Gameboy_Bootstrap_ROM
*/

